"""فهرستِ آیکون‌های ادمین را از اسپرایتِ محلیِ Lucide می‌سازد.

خروجی ``static/admin/js/lucide_icons.js`` یعنی ``window.__LUCIDE_ICONS = [...]``
که ``static/admin/js/icon_picker.js`` مصرف می‌کند. خودِ موتورِ رندر و
اعتبارسنجیِ پایتون نام‌ها را مستقیم از اسپرایت پارِس می‌کنند و به این
فایل نیازی ندارند؛ این اسکریپت فقط به‌روزرسانیِ فهرستِ ادمین است — هر بار
که اسپرایت به‌روز شد اجراش کنید:
    venv\\Scripts\\python scripts\\build_lucide_icons.py

در همین حین جدولِ ``LEGACY_ALIASES`` (apps/core/icon_utils.py) هم
اعتبارسنجی می‌شود تا هیچ نگاشتِ قدیمی به آیکونی که این نسخه از اسپرایت
ندارد منجر نشود.
"""

import io
import json
import os
import re
import sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BASE)
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")

import django  # noqa: E402

django.setup()

from apps.core.icon_utils import LEGACY_ALIASES  # noqa: E402

SPRITE_REL = os.path.join("static", "lucide", "sprite.svg")
OUT_REL = os.path.join("static", "admin", "js", "lucide_icons.js")

svg = io.open(os.path.join(BASE, SPRITE_REL), encoding="utf-8").read()
names = sorted(set(re.findall(r'<symbol id="([a-z0-9][a-z0-9-]*)"', svg)))

missing = [(k, v) for k, v in LEGACY_ALIASES.items() if v not in set(names)]
if missing:
    for k, v in missing:
        print("MISSING alias target: %s -> %s" % (k, v))
    sys.exit("LEGACY_ALIASES به آیکون‌های بیرون از اسپرایت اشاره می‌کند.")

names_json = json.dumps(names, separators=(",", ":"))
aliases_json = json.dumps(LEGACY_ALIASES, separators=(",", ":"), ensure_ascii=False)
header = (
    "/* Generated by scripts/build_lucide_icons.py — do not edit.\n"
    " * window.__LUCIDE_ICONS = [ ... Lucide icon names from the sprite ... ]\n"
    " * window.__LUCIDE_ALIASES = { legacyName: lucideName, ... }\n"
    " */\n"
)
out = os.path.join(BASE, OUT_REL)
io.open(out, "w", encoding="utf-8", newline="").write(
    header
    + "window.__LUCIDE_ICONS = " + names_json + ";\n"
    + "window.__LUCIDE_ALIASES = " + aliases_json + ";\n"
)
print("%d names -> %s" % (len(names), OUT_REL))
