"""فهرستِ آیکون‌های ادمین را از وبفونتِ محلیِ Tabler می‌سازد.

خروجی ``static/admin/js/tabler_icons.js`` یعنی ``window.__TI_ICONS = [...]``
که ``static/admin/js/icon_picker.js`` مصرف می‌کند. خودِ موتورِ رندر و
اعتبارسنجیِ پایتون نام‌ها را مستقیم از CSS پارِس می‌کنند و به این فایل
نیازی ندارند؛ این اسکریپت فقط یک فرتِ یکسره است و هر بار که فونت به‌روز شد
دارَش اجراش کنید:
    venv\\Scripts\\python scripts\\build_tabler_icons.py

در همین حین جدولِ ``LEGACY_ALIASES`` (apps/core/icon_utils.py) هم اعتبارسنجی
می‌شود تا هیچ نگاشتِ قدیمی به آیکونی که این نسخه از فونت ندارد منجر نشود.
"""

import io
import json
import os
import re
import sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BASE)

CSS_REL = os.path.join("static", "tabler", "tabler-icons.min.css")
OUT_REL = os.path.join("static", "admin", "js", "tabler_icons.js")

css = io.open(os.path.join(BASE, CSS_REL), encoding="utf-8").read()
names = sorted(set(re.findall(r"\.ti-([a-z0-9-]+):before", css)))

# --- اعتبارسنجیِ جدولِ نگاشتِ قدیمی ---
from apps.core.icon_utils import LEGACY_ALIASES  # noqa: E402

missing = [(k, v) for k, v in LEGACY_ALIASES.items() if v not in set(names)]
if missing:
    for k, v in missing:
        print("MISSING alias target: %s -> %s" % (k, v))
    sys.exit("LEGACY_ALIASES به آیکون‌های بیرون از فونت اشاره می‌کند.")

payload = json.dumps(names, separators=(",", ":"))
aliases = json.dumps(LEGACY_ALIASES, separators=(",", ":"), ensure_ascii=False)
header = (
    "/* Generated by scripts/build_tabler_icons.py — do not edit.\n"
    " * window.__TI_ICONS = [ ... Tabler Icons names ... ]\n"
    " * window.__TI_ALIASES = { legacyName: tablerName, ... }\n"
    " */\n"
)
out = os.path.join(BASE, OUT_REL)
io.open(out, "w", encoding="utf-8", newline="").write(
    header
    + "window.__TI_ICONS = " + payload + ";\n"
    + "window.__TI_ALIASES = " + aliases + ";\n"
)
print("%d names -> %s" % (len(names), OUT_REL))
