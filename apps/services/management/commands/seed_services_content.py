    def seed_service(self, service, spec):
        created = 0
        created += self.fill_hero(service, spec)
        created += self.seed_children(service, spec)
        created += self.seed_plans(service, spec)
        created += self.seed_related(service, spec)
        service.save()
        return created

    # ── خدمات مرتبط: فقط وقتی هنوز هیچ‌کدام انتخاب نشده‌اند ──
    def seed_related(self, service, spec):
        slugs = spec.get("related") or []
        if not slugs or service.related_services.exists():
            return 0
        related = list(
            Service.objects.filter(slug__in=slugs).exclude(pk=service.pk)
        )
        service.related_services.add(*related)
        return len(related)

    # ── هیرو و سئو: فقط پرکردنِ فیلدهای خالی ──
    def fill_hero(self, service, spec):
        created = 0
        hero = spec["hero"]
        pairs = {
            "hero_eyebrow": hero["eyebrow"],
            "hero_title": hero["title"],
            "hero_lead": hero["lead"],
            "hero_cta_primary_text": hero["primary_text"],
            "hero_cta_primary_url": hero["primary_url"],
            "hero_cta_secondary_text": hero["secondary_text"],
            "hero_cta_secondary_url": hero["secondary_url"],
            "meta_title": spec["meta_title"],
            "meta_description": spec["meta_description"],
        }
        for field, value in pairs.items():
            if not getattr(service, field) and value:
                setattr(service, field, value)
                created += 1
        # لهجهٔ رنگی فقط وقتی هنوز روی پیش‌فرضِ مدل است تنظیم می‌شود.
        if service.accent == "gold" and spec.get("accent"):
            service.accent = spec["accent"]
        return created

    # ── فرزندانِ ترتیبی: get_or_create + پاکسازیِ ردیف‌های v1 ──
    def seed_children(self, service, spec):
        created = 0

        created += self._seed_collection(
            ServiceStat, service, spec.get("stats", []),
            key="label", fields=lambda row: {
                "number": row[0],
                "label": row[1],
                "description": row[2] if len(row) > 2 else "",
            },
        )
        created += self._seed_collection(
            ServiceWhyUs, service, spec.get("why", []),
            key="title", fields=lambda row: {"icon": row[0], "title": row[1], "description": row[2]},
        )
        created += self._seed_collection(
            ServiceDeliverable, service, spec.get("deliverables", []),
            key="title", fields=lambda row: {"title": row[0] if isinstance(row, tuple) else row},
        )
        created += self._seed_collection(
            ServiceProcess, service, spec.get("process", []),
            key="title",
            fields=lambda row: {
                "title": row[0] if isinstance(row, tuple) else row,
                "description": row[1] if isinstance(row, tuple) and len(row) > 1 else "",
            },
            # توضیحاتِ مراحل فقط برای ردیف‌هایی پر می‌شوند که خالی‌اند — یعنی
            # ردیف‌هایی که خودِ این seed ساخته. ویرایشِ ادمین هرگز بازنویسی نمی‌شود.
            fill_empty=("description",),
        )
        created += self._seed_collection(
            ServiceTool, service, spec.get("tools", []),
            key="name", fields=lambda row: {
                "name": row[0] if isinstance(row, tuple) else row,
                "icon": row[1] if isinstance(row, tuple) and len(row) > 1 else "",
            },
        )
        created += self._seed_collection(
            ServiceUseCase, service, spec.get("use_cases", []),
            key="title", fields=lambda row: {
                "icon": row[0],
                "title": row[1],
                "description": row[2] if len(row) > 2 else "",
            },
        )
        created += self._seed_sections(service, spec.get("sections", []))
        created += self._seed_faqs(service, spec.get("faqs", []))
        return created

    def _seed_collection(self, model, service, rows, key, fields, fill_empty=()):
        """الگوی D21: ردیف‌هایی که کلیدشان در لیستِ جدید نیست حذف می‌شوند
        (همان محتوای v1 که این seed ساخته)، بقیه get_or_create می‌شوند.

        ``fill_empty`` فیلدهایی هستند که روی ردیف‌های از پیش موجود فقط وقتی
        نوشته می‌شوند که خالی باشند — برای پرکردنِ یک فیلدِ جدیدِ اختیاری روی
        ردیف‌هایی که این seed قبلاً ساخته، بدون بازنویسیِ ویرایشِ ادمین."""
        keys = []
        created = 0
        for index, row in enumerate(rows):
            attrs = fields(row)
            keys.append(attrs[key])
            obj, created_now = model.objects.get_or_create(
                service=service,
                **{key: attrs[key]},
                defaults={**attrs, "order": index},
            )
            created += int(created_now)
            if created_now or not fill_empty:
                continue
            updates = {
                name: attrs[name]
                for name in fill_empty
                if attrs.get(name) and not getattr(obj, name)
            }
            if updates:
                model.objects.filter(pk=obj.pk).update(**updates)
        stale = model.objects.filter(service=service).exclude(**{f"{key}__in": keys})
        stale.delete()
        return created

    def _seed_sections(self, service, sections):
        created = 0
        for index, section in enumerate(sections):
            _, created_now = ServiceSection.objects.get_or_create(
                service=service,
                title=section["title"],
                defaults={
                    "eyebrow": section.get("eyebrow", ""),
                    "body": section["body"],
                    "layout": section.get("layout", "right"),
                    "order": index,
                    "is_active": True,
                },
            )
            created += int(created_now)
        return created

    def _seed_faqs(self, service, faqs):
        created = 0
        for index, (question, answer) in enumerate(faqs):
            _, created_now = ServiceFAQ.objects.get_or_create(
                service=service,
                question=question,
                defaults={"answer": answer, "order": index},
            )
            created += int(created_now)
        # پاکسازیِ سوالاتِ v1ِ این خدمت که در لیستِ جدید نیستند.
        questions = [q for q, _ in faqs]
        ServiceFAQ.objects.filter(service=service).exclude(question__in=questions).delete()
        return created

    # ── پلن‌ها: get_or_create بر اساسِ (service, plan_type) ──
    # اگر پلن از قبل وجود دارد (مثل پلن‌های v1ِ «طراحی سایت») فیلدهایش دست‌نخورده
    # می‌مانند و فقط ویژگی‌هایش ساخته می‌شوند — قیمت‌ها و نام‌های ادمین حفظ می‌شوند.
    def seed_plans(self, service, spec):
        plans = spec.get("plans")
        if not plans:
            return 0
        created = 0
        for index, plan in enumerate(plans):
            obj, created_now = ServicePlan.objects.get_or_create(
                service=service,
                plan_type=plan["plan_type"],
                defaults={
                    "name": plan["name"],
                    "tagline": plan.get("tagline", ""),
                    "price": plan.get("price"),
                    "price_prefix": "از",
                    "price_currency": "تومان",
                    "price_note": plan.get("price_note", ""),
                    "cta_label": "ثبت سفارش",
                    "cta_url": CONTACT,
                    "is_featured": plan.get("featured", False),
                    "is_active": True,
                    "order": index,
                },
            )
            created += int(created_now)
            for feature_index, (title, included) in enumerate(plan["features"]):
                _, fc = ServicePlanFeature.objects.get_or_create(
                    plan=obj,
                    title=title,
                    defaults={"included": included, "order": feature_index},
                )
                created += int(fc)
        return created
